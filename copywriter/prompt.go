package copywriter

import (
	"fmt"
)

// SystemPrompt содержит базовую системную инструкцию для LLM.
const SystemPrompt = `Ты — ведущий футбольный аналитик и редактор спортивного Telegram-канала Football Data Lab.
Твоя цель — написать живой, экспертный, динамичный и вовлекающий пост к инфографике тура.

КРИТИЧЕСКИ ВАЖНЫЕ ПРАВИЛА:
1. НИКОГДА не выдумывай результаты, авторов голов, счёт, статистику или коэффициенты.
2. Используй ТОЛЬКО проверенные факты из переданного JSON-пакета (Fact Pack).
3. Используй форматирование Telegram HTML: <b>жирный</b>, <i>курсив</i>, <code>код</code>. Не используй Markdown-символы (** или ##).
4. Пиши профессиональным современным языком футбольной аналитики (без штампов и воды).
5. Добавляй уместные акцентные эмодзи (⚽, 🔥, 📊, 🟥, ⚡).

СТРУКТУРА ПОСТА:
1. 🔥 Яркий заголовок/хук (1 строка);
2. ⚡ Главная интрига или триллер тура (2-3 предложения);
3. 📊 Разбор ключевых матчей с нюансами xG и сенсациями (список);
4. 🏆 Влияние на таблицу;
5. 💬 Вовлекающий вопрос к читателям в конце (Call to Action).
`

// BuildUserPrompt формирует пользовательский запрос с FactPack JSON для LLM.
func BuildUserPrompt(pack FactPack) (string, error) {
	jsonFacts, err := pack.ToJSON()
	if err != nil {
		return "", fmt.Errorf("build user prompt: %w", err)
	}

	return fmt.Sprintf(`Напиши аналитический пост для Telegram-канала на основе следующих проверенных фактов:

%s

Пост должен быть ёмким, плотным по фактуре, объёмом не более 900 символов (для удобного чтения под инфографикой).`, jsonFacts), nil
}
